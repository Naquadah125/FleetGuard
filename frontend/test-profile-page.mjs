import assert from 'node:assert/strict'
import fs from 'node:fs'

const app = fs.readFileSync('./src/App.jsx', 'utf8')
const adminLayout = fs.readFileSync('./src/pages/admin/AdminLayout.jsx', 'utf8')
const driverLayout = fs.readFileSync('./src/pages/driver/DriverLayout.jsx', 'utf8')
const profilePage = fs.readFileSync('./src/pages/profile/ProfilePage.jsx', 'utf8')
const profileStyles = fs.readFileSync('./src/pages/profile/ProfilePage.module.css', 'utf8')
const authContext = fs.readFileSync('./src/context/AuthContext.jsx', 'utf8')
const adminEmployees = fs.readFileSync('./src/pages/admin/AdminEmployees.jsx', 'utf8')
const adminCameras = fs.readFileSync('./src/pages/admin/AdminCameras.jsx', 'utf8')

assert.match(app, /path="profile" element={<ProtectedRoute allowedRoles=\{\['ADMIN', 'FLEET_ADMIN'\]\}><ProfilePage \/><\/ProtectedRoute>} \/>/)
assert.match(app, /path="profile" element={<ProtectedRoute allowedRoles=\{\['USER', 'DRIVER'\]\}><DriverProfilePage \/><\/ProtectedRoute>} \/>/)
assert.match(app, /allowedRoles=\{\['USER', 'DRIVER'\]\}/)
assert.match(app, /allowedRoles=\{\['ADMIN', 'FLEET_ADMIN'\]\}/)
assert.match(adminLayout, /Chỉnh sửa thông tin/)
assert.match(driverLayout, /Chỉnh sửa thông tin/)
assert.match(profilePage, /dateOfBirth/)
assert.match(profilePage, /readOnly/)
assert.match(profilePage, /updateUser\(data\.user\)/)
assert.match(authContext, /avatarColor: nextUser\.avatarColor/)
assert.match(authContext, /avatarImage: nextUser\.avatarImage/)
assert.match(profilePage, /type="file"/)
assert.match(profilePage, /accept="image\/jpeg,image\/png,image\/webp"/)
assert.match(profilePage, /aria-label="Xem trước thẻ hồ sơ"/)
assert.match(profilePage, /avatarImage/)
assert.match(profilePage, /roleLabels/)
assert.match(profileStyles, /grid-template-columns:\s*minmax\(0,\s*1fr\)\s+320px/)
assert.match(adminLayout, /user\?\.avatarImage/)
assert.match(driverLayout, /user\?\.avatarImage/)
assert.match(adminEmployees, /row\.avatarImage/)
assert.match(adminCameras, /driver\.avatarImage/)
assert.match(profilePage, /gender/)
assert.ok(!profilePage.includes('Màu avatar'))
assert.match(profileStyles, /background:\s*#ffffff/)
assert.match(authContext, /gender: nextUser\.gender/)
console.log('Profile page UI contract test passed.')
