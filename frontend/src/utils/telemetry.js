export function buildTelemetryPayload({
  sessionId,
  driverId,
  organizationId = null,
  vehicleId = null,
  timestamp = Date.now(),
  emotion = 'neutral',
  confidence = 0.5,
  scores = {},
  ear = 0,
  mar = 0,
  perclos = 0,
  yaw = 0,
  pitch = 0,
  level = 0,
  status = 'NORMAL',
  yawnCount = 0,
}) {
  return {
    session_id: sessionId || 'default_session',
    driver_id: driverId || 'default_driver',
    organization_id: organizationId,
    vehicle_id: vehicleId,
    timestamp,
    emotion,
    emotion_confidence: confidence,
    emotion_scores: scores,
    ear,
    mar,
    perclos,
    head_pose: { yaw, pitch, roll: 0 },
    alert_level: level,
    status,
    yawn_count: yawnCount,
  }
}
